#!/usr/bin/env python3
"""
Microsoft Sentinel Analytics Rule & Playbook Generator.
Generates declarative ARM / JSON templates for Sentinel Scheduled Analytics Rules
with mapped entities, query frequency, trigger thresholds, and automation settings.

Usage:
    python3 sentinel_playbook_generator.py --rule-name "Detect-GlobalAdmin-RoleAssignment" --severity High
    python3 sentinel_playbook_generator.py --rule-name "Detect-Impossible-Travel" --output rule.json
"""

import argparse
import json
import sys
from typing import Dict, Any, List

def build_sentinel_alert_rule(
    name: str,
    severity: str,
    query_str: str,
    tactics: List[str],
    frequency: str = "PT5M",
    period: str = "PT15M"
) -> Dict[str, Any]:
    arm_template = {
        "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
        "contentVersion": "1.0.0.0",
        "parameters": {
            "workspaceName": {
                "type": "string",
                "defaultValue": "law-sentinel-prod",
                "metadata": {
                    "description": "Log Analytics Workspace housing Sentinel"
                }
            }
        },
        "resources": [
            {
                "type": "Microsoft.OperationalInsights/workspaces/providers/alertRules",
                "name": f"[concat(parameters('workspaceName'), '/Microsoft.SecurityInsights/', '{name}')]",
                "apiVersion": "2022-11-01-preview",
                "kind": "Scheduled",
                "properties": {
                    "displayName": name.replace("-", " "),
                    "description": f"Automated detection rule generated by Open Cloud Agents. Monitors for {name}.",
                    "severity": severity,
                    "enabled": True,
                    "query": query_str.strip(),
                    "queryFrequency": frequency,
                    "queryPeriod": period,
                    "triggerOperator": "GreaterThan",
                    "triggerThreshold": 0,
                    "suppressionDuration": "PT1H",
                    "suppressionEnabled": False,
                    "tactics": tactics,
                    "incidentConfiguration": {
                        "createIncident": True,
                        "groupingConfiguration": {
                            "enabled": True,
                            "reopenClosedIncident": False,
                            "lookbackDuration": "PT5H",
                            "matchingMethod": "Selected",
                            "groupByEntities": ["Account", "IP"]
                        }
                    },
                    "entityMappings": [
                        {
                            "entityType": "Account",
                            "fieldMappings": [
                                {
                                    "identifier": "UserPrincipalName",
                                    "columnName": "AccountCustomEntity"
                                }
                            ]
                        },
                        {
                            "entityType": "IP",
                            "fieldMappings": [
                                {
                                    "identifier": "Address",
                                    "columnName": "IPCustomEntity"
                                }
                            ]
                        }
                    ]
                }
            }
        ]
    }
    return arm_template

def main():
    parser = argparse.ArgumentParser(description="Microsoft Sentinel Analytics Rule Generator")
    parser.add_argument("--rule-name", default="Detect-Anomalous-SignIns", help="Rule name identifier")
    parser.add_argument("--severity", choices=["High", "Medium", "Low", "Informational"], default="High", help="Alert severity")
    parser.add_argument("--tactics", default="InitialAccess,PrivilegeEscalation", help="Comma-separated MITRE ATT&CK tactics")
    parser.add_argument("--frequency", default="PT5M", help="ISO 8601 query frequency (e.g. PT5M)")
    parser.add_argument("--period", default="PT15M", help="ISO 8601 query lookback period (e.g. PT15M)")
    parser.add_argument("--kql", help="Custom KQL query string (defaults to template query if omitted)")
    parser.add_argument("--output", help="Write template to output file")

    args = parser.parse_args()

    default_kql = """
SigninLogs
| where TimeGenerated > ago(15m)
| where ResultType == 0
| extend AccountCustomEntity = UserPrincipalName
| extend IPCustomEntity = IPAddress
| project TimeGenerated, UserPrincipalName, IPAddress, AppDisplayName, Location, AccountCustomEntity, IPCustomEntity
"""
    query_str = args.kql if args.kql else default_kql
    tactics_list = [t.strip() for t in args.tactics.split(",") if t.strip()]

    rule_template = build_sentinel_alert_rule(
        name=args.rule_name,
        severity=args.severity,
        query_str=query_str,
        tactics=tactics_list,
        frequency=args.frequency,
        period=args.period
    )

    rendered = json.dumps(rule_template, indent=2)

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(rendered)
        print(f"✔ Sentinel ARM template written to {args.output}")
    else:
        print(rendered)

if __name__ == "__main__":
    main()
