#!/usr/bin/env python3
"""
Sysdig Secure Runtime & Drift Control Policy Generator.
Generates declarative JSON policy definitions for Sysdig Secure enforcement.

Usage:
    python3 sysdig_policy_generator.py --policy-name "prod-drift-prevention" --action kill --block-drift
    python3 sysdig_policy_generator.py --output prod-policy.json
"""

import argparse
import json
import sys
from typing import List, Dict, Any

def build_sysdig_policy(
    name: str,
    action_type: str,
    action_target: str,
    block_drift: bool,
    scope: str,
    severity: int,
    exceptions: List[str]
) -> Dict[str, Any]:
    actions = []
    if action_type in ("kill", "stop", "pause"):
        actions.append({
            "type": action_type,
            "target": action_target
        })
    # Always include incident capture action for forensic auditing
    actions.append({
        "type": "capture",
        "duration_seconds": 30,
        "pre_trigger_seconds": 10
    })

    exception_list = []
    for exc in exceptions:
        if exc.strip():
            exception_list.append({
                "executable_path": exc.strip(),
                "description": "Whitelisted binary execution"
            })

    policy = {
        "name": name,
        "description": f"Automated policy generated by Open Cloud Agents. Enforces {action_type} on unauthorized runtime actions.",
        "severity": severity,
        "enabled": True,
        "scope": scope,
        "actions": actions,
        "drift_control": {
            "enabled": block_drift,
            "prevent_execution": block_drift,
            "deny_new_executables": block_drift,
            "deny_modified_executables": block_drift
        },
        "runtime_rules": [
            {
                "rule_name": "Terminal Shell in Container",
                "action": action_type
            },
            {
                "rule_name": "Write below etc or sensitive directory",
                "action": action_type
            },
            {
                "rule_name": "Suspicious outbound network connection",
                "action": action_type
            }
        ],
        "exceptions": exception_list
    }
    return policy

def main():
    parser = argparse.ArgumentParser(description="Sysdig Secure Policy Generator")
    parser.add_argument("--policy-name", default="Production Container Hardening Policy", help="Descriptive policy name")
    parser.add_argument("--action", choices=["kill", "stop", "pause", "notify"], default="kill", help="Prevention action to take")
    parser.add_argument("--target", choices=["process", "container"], default="process", help="Target of the kill action")
    parser.add_argument("--block-drift", action="store_true", default=True, help="Enable container executable drift prevention")
    parser.add_argument("--scope", default="kubernetes.namespace.name in ('production')", help="Scope filter expression")
    parser.add_argument("--severity", type=int, default=7, help="Severity level (1-7, 7 being highest)")
    parser.add_argument("--exceptions", default="", help="Comma-separated list of whitelisted binary paths")
    parser.add_argument("--output", help="Write policy JSON to file")

    args = parser.parse_args()

    exc_list = [x.strip() for x in args.exceptions.split(",") if x.strip()]
    policy = build_sysdig_policy(
        name=args.policy_name,
        action_type=args.action,
        action_target=args.target,
        block_drift=args.block_drift,
        scope=args.scope,
        severity=args.severity,
        exceptions=exc_list
    )

    rendered = json.dumps(policy, indent=2)

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(rendered)
        print(f"✔ Sysdig policy written to {args.output}")
    else:
        print(rendered)

if __name__ == "__main__":
    main()
